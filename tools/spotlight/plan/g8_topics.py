THEMES = [(n, re.compile(r'(?:^|[^а-яё])(?:' + p + ')', re.I)) for n, p in THEMES]
POS = lambda p: (p or '').strip().lower()
def kind(r):
    p = POS(r['pos'])
    if p.startswith('v') or p in ('n, v',): return 'v'
    if p.startswith('adj'): return 'adj'
    if p.startswith('n') or p == 'c n': return 'n'
    if p in ('adv', 'conj', 'prep', 'pos', 'adj/adv'): return 'other'
    return 'phrase'
def noun_theme(r):
    tr = r['translation'].lower().replace('ё', 'е')
    for name, rx in THEMES:
        if rx.search(' ' + tr): return name
    return None
by = collections.OrderedDict()
for r in rows:
    base = r['section'].replace(' Phrasals & Phrases', '').replace(' Phrasal verbs', '').replace(' Phrases', '')
    phr = base != r['section']
    by.setdefault((r['module'], base), []).append((r, phr))
out = {}
for (mod, base), items in by.items():
    main = [r for r, phr in items if not phr]
    phrs = [r for r, phr in items if phr]
    # фразы урока
    for r in phrs:
        out[id(r)] = 'фразы' if len(phrs) >= 4 else '@фразы'
    if len(main) <= 15:
        for r in main:
            out[id(r)] = '' if kind(r) != 'other' or len(main) <= 6 else '@полезные слова'
        continue
    groups = collections.defaultdict(list)
    for r in main:
        k = kind(r)
        if k == 'n':
            g = noun_theme(r) or 'понятия'
        elif k == 'v': g = 'действия'
        elif k == 'adj': g = 'описание'
        elif k == 'other': g = '@полезные слова'
        else: g = 'фразы'
        groups[g].append(r)
    # маленькая тема существительных (<4) → «понятия» этого же урока
    for g in [g for g in groups if g not in ('понятия', 'действия', 'описание', 'фразы') and not g.startswith('@')]:
        if len(groups[g]) < 4:
            groups['понятия'] += groups.pop(g)
    for g, rs in groups.items():
        if g.startswith('@'):
            name = g
        elif len(rs) < 4:
            name = '@' + {'понятия': 'предметы и понятия'}.get(g, g)
        else:
            name = g
        for r in rs: out[id(r)] = name
    # если в уроке остались одна-две колоды и одна из них «фразы» урока — это нормально
with open('plan/g8_topics.tsv', 'w', newline='') as f:
    f.write('module\tsection\tterm\ttopic\n')
    for r in rows:
        f.write('\t'.join((r['module'], r['section'], r['term'], out[id(r)])) + '\n')
c = collections.Counter(out.values())
print(len(rows), sorted(c.items(), key=lambda x: -x[1]))
