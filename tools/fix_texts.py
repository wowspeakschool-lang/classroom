def main():
    for n, pairs in EDITS.items():
        path = os.path.join(LESSONS, "lesson-%d.html" % n)
        s = open(path, encoding="utf-8").read()
        done, already, missing = 0, 0, []
        for old, new in pairs:
            if old in s:
                s = s.replace(old, new, 1); done += 1
            elif new in s:
                already += 1
            else:
                missing.append(old[:40] + "…")
        open(path, "w", encoding="utf-8").write(s)
        note = ", уже стояло %d" % already if already else ""
        print("Урок %d: заменено %d%s%s" % (n, done, note,
              ("; НЕ НАЙДЕНО: " + "; ".join(missing)) if missing else ""))


if __name__ == "__main__":
    main()
