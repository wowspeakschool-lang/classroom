with d as (
  select b.id,
         jsonb_agg(
           case
             when (x->>'prompt') ~ '[А-Яа-я]' then x
             when ru.r is null then x
             when coalesce(x->>'prompt','') = '' then jsonb_set(x, '{prompt}', to_jsonb(ru.r))
             else jsonb_set(x, '{prompt}', to_jsonb((x->>'prompt') || '  (' || ru.r || ')'))
           end order by o) as arr
  from classroom_blocks b
  join classroom_lessons l on l.id = b.lesson_id,
       jsonb_array_elements(b.payload->'items') with ordinality as q(x, o)
  left join ru on ru.w = x->'accept'->>0
  where b.type = 'exact_input' and l.kind = 'test'
  group by b.id
)
update classroom_blocks b
set payload = jsonb_set(b.payload, '{items}', d.arr)
from d where b.id = d.id;
