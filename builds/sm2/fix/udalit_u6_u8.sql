 ('7af7746a-7703-4242-bce2-ec146d6fa314'::uuid),  -- u6 ДЗ1 text «Соедини картинку со словом»
 ('a0ff5cce-20ab-4a9b-9bba-1c5211adfed7'::uuid),  -- u6 ДЗ1 text «Посмотри на картинки и напиши слова»
 ('bcf726de-aaa0-4ce7-8d6c-d360dd87bc64'::uuid),  -- u7 ДЗ1 match слово↔перевод
