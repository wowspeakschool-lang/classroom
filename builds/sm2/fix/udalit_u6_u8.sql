-- блоков в задетых уроках, так что дыр в sort_order не останется.
--
-- ЧТО И ПОЧЕМУ
--
-- 1. Три блока «Найди пару: слово и перевод» — ДЗ 1 юнитов 6, 7 и 8, блок 7.
--    Решение Анны от 22.10: задания «слово ↔ перевод» переделываем в
--    «слово ↔ картинка». В этих трёх уроках такой блок уже стоит рядом
--    (блок 6, «Соедини картинку со словом») и на том же наборе слов —
--    переделка дала бы два одинаковых задания подряд. Поэтому переводную
--    пару снимаем, картиночная остаётся.
--    После удаления в ДЗ 1 остаётся: юнит 6 — 10 заданий, юнит 7 — 9,
--    юнит 8 — 8. Все выше ориентира в 8.
--
-- 2. Четыре текстовых блока-подводки, которые после перестановки блоков
--    (правила раздела 3а брифа) остались без своего задания:
--      * юнит 6, ДЗ 1, блок 15 «Отлично! Продолжаем 💪 Соедини картинку со
--        словом» — задание переехало вверх, к узнаванию, и его открывает
--        блок 9 «Теперь будем писать слова ✍️»;
--      * юнит 6, ДЗ 1, блок 16 «Посмотри на картинки и напиши слова»
--        — то же самое;
--      * юнит 7, ДЗ 1, блок 15 «Смотри на картинки и вписывай слова»
--        — дублирует разделитель «Теперь будем писать слова ✍️» (блок 9);
--      * юнит 7, ДЗ 1, блок 16 «Правда или нет?» — дублирует заголовок
--        самого блока `truefalse`, который теперь стоит выше (блок 8).
--    Текстовые блоки с карточками методиста (`card_*.webp`) НЕ удаляются:
--    из них убрана только дублирующая фраза-подводка, картинка осталась.
--
-- Все четыре текстовых блока стоят перед прощанием, так что до запуска
-- этого файла прощание в уроке остаётся последним.

begin;

create temporary table udalyaem_sm2_u68 (id uuid) on commit drop;
insert into udalyaem_sm2_u68 (id) values
