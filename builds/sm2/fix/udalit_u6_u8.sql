 ('86d83f77-bc2f-47ae-9269-48a1670d7da2'::uuid);  -- u8 ДЗ1 match слово↔перевод

create temporary table zatronutye_uroki_sm2_u68 on commit drop as
select distinct lesson_id from classroom_blocks where id in (select id from udalyaem_sm2_u68);

delete from classroom_blocks where id in (select id from udalyaem_sm2_u68);

-- нумерация блоков снова подряд с нуля
with novyy as (
  select b.id, row_number() over (partition by b.lesson_id order by b.sort_order) - 1 as n
  from classroom_blocks b
  where b.lesson_id in (select lesson_id from zatronutye_uroki_sm2_u68))
update classroom_blocks b set sort_order = novyy.n + 1000
from novyy where b.id = novyy.id;

update classroom_blocks set sort_order = sort_order - 1000
where lesson_id in (select lesson_id from zatronutye_uroki_sm2_u68) and sort_order >= 1000;

commit;
