update classroom_blocks b
set payload = jsonb_set(b.payload, '{cards}', (
  select coalesce(jsonb_agg(
    case when coalesce(x->>'translation','')='' and s.tr is not null
         then x || jsonb_build_object('translation', s.tr) else x end order by i), '[]'::jsonb)
  from jsonb_array_elements(b.payload->'cards') with ordinality a(x, i)
  left join slovar s on s.t = x->>'text'))
where b.type = 'flashcards'
  and b.lesson_id in (select l.id from classroom_lessons l
       join classroom_units u on u.id = l.unit_id
       join classroom_courses c on c.id = u.course_id
       where c.slug like 'wow-dragon%')
  and (select count(*) from jsonb_array_elements(b.payload->'cards') x
       where coalesce(x->>'translation','')='' and coalesce(x->>'text','')<>'') > 0;
