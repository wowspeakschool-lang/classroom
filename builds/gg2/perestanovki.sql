-- Go Getter 2 — три расхождения с планами уроков, которые чинятся перестановкой
-- блоков (отчёт: builds/gg2/sverka_s_planami.md, пункты 2, 3, 4).
-- 03.11.2026. Юнит 4 и юниты 5-8 не трогаем.
--
-- Уроки:
--   U1 ДЗ 3  ed03a12f-2fd8-4e50-96a6-e889f97107e5   (12 блоков)
--   U1 ДЗ 4  851d9b90-f06b-46e5-8fd5-96cec97d6d69   (12 блоков)
--   U2 ДЗ 3  d8fbeb71-a2ef-4bfd-a0d9-eb73dae5d5e0   (10 блоков)
--   U2 ДЗ 4  edb04172-9975-4411-bda8-74f5592a7a13   ( 9 блоков)
--   U3 ДЗ 3  118e1ff0-aff7-4b88-bdb3-e16a2f10d1eb   (22 блока)
--   U3 ДЗ 4  9c298871-50b1-4392-b74a-e436e93e54a9   (12 блоков)

-- ===========================================================================
-- 0. Бэкап всех шести уроков
-- ===========================================================================

create table if not exists classroom_backup_gg2_perestanovki_20261103 as
select * from classroom_blocks
where lesson_id in (
  'ed03a12f-2fd8-4e50-96a6-e889f97107e5',
  '851d9b90-f06b-46e5-8fd5-96cec97d6d69',
  'd8fbeb71-a2ef-4bfd-a0d9-eb73dae5d5e0',
  'edb04172-9975-4411-bda8-74f5592a7a13',
  '118e1ff0-aff7-4b88-bdb3-e16a2f10d1eb',
  '9c298871-50b1-4392-b74a-e436e93e54a9'
);

-- ===========================================================================
-- 1. Юнит 1, ДЗ 3, блок 9: вычистить do/play
-- ===========================================================================
-- Блок был смешанный: строки 1-2 — вспомогательный Do/Does (материал урока 3),
-- строки 3-6 — лексический выбор do/play (ballet, chess, football, homework),
-- то есть материал урока 4. Переносить нечего: в ДЗ 4 do/play уже отработано
-- трижды (блок 8 — правило, блок 9 — sort do/play, блок 10 — gaps choice
-- с теми же ballet/chess/football/basketball/karate/pottery). Поэтому строки
-- 3-6 удаляются, остаётся чистый Do/Does, и из заголовка убирается «Do or play?».
-- Блоки не двигаются, sort_order не меняется.

update classroom_blocks
set payload = $blk${"mode": "drag", "text": "1. __Do__ you play tennis at the weekend?\n2. __Does__ your brother do karate?", "title": "Do или Does? Перетащи слова в пропуски"}$blk$::jsonb
where lesson_id = 'ed03a12f-2fd8-4e50-96a6-e889f97107e5'
  and sort_order = 8
  and type = 'gaps';

-- ===========================================================================
-- 2. Юнит 2: лексика «ёмкости» из ДЗ 3 в ДЗ 4
-- ===========================================================================
-- Переезжают четыре блока ДЗ 3 (номера в редакторе 2-5):
--   2 flashcards  bar/bottle/can/carton/jar/packet
--   3 quiz        «Послушай слово и выбери картинку»
--   4 match       «Соедини картинку с выражением»
--   5 gaps(drag)  «a __bar__ of chocolate …»
-- В ДЗ 3 остаётся только how much / how many — ровно то, что в плане урока 3.
-- В ДЗ 4 карточки становятся вторым блоком, дальше лесенка: на слух -> глазами
-- -> вписать с опорой, и только после этого прежняя часть «в кафе».

-- парковка, чтобы не драться за уникальный ключ (lesson_id, sort_order)
update classroom_blocks set sort_order = sort_order + 2000
where lesson_id = 'edb04172-9975-4411-bda8-74f5592a7a13';
update classroom_blocks set sort_order = sort_order + 1000
where lesson_id = 'd8fbeb71-a2ef-4bfd-a0d9-eb73dae5d5e0';

-- переезд
update classroom_blocks set lesson_id = 'edb04172-9975-4411-bda8-74f5592a7a13'
where lesson_id = 'd8fbeb71-a2ef-4bfd-a0d9-eb73dae5d5e0'
  and sort_order in (1001, 1002, 1003, 1004);

-- окончательная нумерация ДЗ 3 (6 блоков)
update classroom_blocks b set sort_order = x.new
from (values (1000,0),(1005,1),(1006,2),(1007,3),(1008,4),(1009,5)) as x(old, new)
where b.lesson_id = 'd8fbeb71-a2ef-4bfd-a0d9-eb73dae5d5e0' and b.sort_order = x.old;

-- окончательная нумерация ДЗ 4 (13 блоков)
update classroom_blocks b set sort_order = x.new
from (values
  (2000,0),            -- приветствие
  (1001,1),            -- карточки ёмкостей
  (1002,2),            -- послушай слово и выбери картинку
  (1003,3),            -- соедини картинку с выражением
  (1004,4),            -- впиши название ёмкости
  (2001,5),            -- где лучше поужинать
  (2002,6),            -- В кафе: диалог с записью
  (2003,7),            -- выбери реплику
  (2004,8),            -- расставь реплики
  (2005,9),            -- ёмкости в диалоге в кафе
  (2006,10),           -- запись речи
  (2007,11),           -- свой диалог
  (2008,12)            -- прощание
) as x(old, new)
where b.lesson_id = 'edb04172-9975-4411-bda8-74f5592a7a13' and b.sort_order = x.old;

-- подводка «Прежде чем приступить к первому заданию…» больше не первая:
-- переформулирована под своё новое место (перед частью «в кафе»).
update classroom_blocks
set payload = jsonb_set(payload, '{html}',
  to_jsonb($blk$<p>Сейчас мы отправимся в кафе. Но сначала подумай, где лучше поужинать: дома или в кафе/ресторане. Что бы ты выбрал?</p><p>Впиши <b>restaurant/cafe</b>, если предпочитаешь есть в кафе или ресторане, или впиши <b>home</b>, если считаешь, что лучшее место, где можно поесть, — это твой дом.</p>$blk$::text))
where lesson_id = 'edb04172-9975-4411-bda8-74f5592a7a13'
  and sort_order = 5 and type = 'task';

-- ===========================================================================
-- 3. Юнит 3: лексика эмоций из ДЗ 3 в ДЗ 4
-- ===========================================================================
-- Переезжают восемь блоков ДЗ 3 (номера в редакторе 14-21):
--   14 text  «а сейчас мы с тобой поговорим об эмоциях»
--   15 match «Соедини названия эмоций с картинками» (7 пар)
--   16 text  «Теперь опиши картинки 🖼️» — заголовок-разделитель серии
--   17-21 task «Опиши картинку · 1…5»
-- В ДЗ 3 остаётся Present Continuous: вопросы и краткие ответы — план урока 3.
-- В ДЗ 4 эмоции идут наверх (вторым блоком — подводка, третьим — лексика),
-- затем своя лесенка до «опиши картинку», и только потом телефонный разговор.

update classroom_blocks set sort_order = sort_order + 2000
where lesson_id = '9c298871-50b1-4392-b74a-e436e93e54a9';
update classroom_blocks set sort_order = sort_order + 1000
where lesson_id = '118e1ff0-aff7-4b88-bdb3-e16a2f10d1eb';

update classroom_blocks set lesson_id = '9c298871-50b1-4392-b74a-e436e93e54a9'
where lesson_id = '118e1ff0-aff7-4b88-bdb3-e16a2f10d1eb'
  and sort_order between 1013 and 1020;

-- окончательная нумерация ДЗ 3 (14 блоков): 1000-1012 -> 0-12, прощание -> 13
update classroom_blocks set sort_order = sort_order - 1000
where lesson_id = '118e1ff0-aff7-4b88-bdb3-e16a2f10d1eb'
  and sort_order between 1000 and 1012;
update classroom_blocks set sort_order = 13
where lesson_id = '118e1ff0-aff7-4b88-bdb3-e16a2f10d1eb'
  and sort_order = 1021;

-- окончательная нумерация ДЗ 4 (20 блоков)
update classroom_blocks b set sort_order = x.new
from (values
  (2000,0),            -- приветствие
  (1013,1),            -- подводка к эмоциям
  (1014,2),            -- соедини эмоции с картинками
  (1015,3),            -- разделитель «Теперь опиши картинки»
  (1016,4),(1017,5),(1018,6),(1019,7),(1020,8),   -- опиши картинку 1-5
  (2001,9),            -- подводка к видео
  (2002,10),           -- видео Samantha / Tony
  (2003,11),           -- соедини вопросы с ответами
  (2004,12),           -- телефонный разговор: выбери реплику
  (2005,13),           -- подводка к разыгранному диалогу
  (2006,14),           -- диалог Елена / папа Эми с записью
  (2007,15),           -- расставь диалог по порядку
  (2008,16),           -- диалог Джанет и миссис Ди
  (2009,17),           -- диалог Джанет и Билли
  (2010,18),           -- напиши свой телефонный разговор
  (2011,19)            -- прощание
) as x(old, new)
where b.lesson_id = '9c298871-50b1-4392-b74a-e436e93e54a9' and b.sort_order = x.old;

-- подводка к эмоциям стоит теперь вторым блоком, а не в середине домашки
update classroom_blocks
set payload = jsonb_set(payload, '{html}',
  to_jsonb($blk$<p>Сначала поговорим об эмоциях 😜</p>$blk$::text))
where lesson_id = '9c298871-50b1-4392-b74a-e436e93e54a9'
  and sort_order = 1 and type = 'text';

-- подводка к видео больше не первая в домашке
update classroom_blocks
set payload = jsonb_set(payload, '{html}',
  to_jsonb($blk$<p>А теперь — видео!</p><ol><li>Сначала посмотри его и найди ответ на вопросы: <i>Where is Samantha? Where is Tony?</i></li><li>После этого выбери персонажа, который понравился тебе больше — Тони или Саманту. Включи видео ещё раз и повторяй за своим героем.</li></ol>$blk$::text))
where lesson_id = '9c298871-50b1-4392-b74a-e436e93e54a9'
  and sort_order = 9 and type = 'text';
